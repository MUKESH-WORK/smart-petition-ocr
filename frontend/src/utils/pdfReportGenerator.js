  const doc = new jsPDF({ orientation: 'portrait', unit: 'mm', format: 'a4' });
  const pageWidth = doc.internal.pageSize.getWidth();
  const margin = 14;
  let currentY = 36;

  addOfficialHeader(doc, 'COMPREHENSIVE PETITION DOSSIER & FULL FORM RECORD');

  const petNumber = petition.petitionNumber || petition.id || 'PET-DOCUMENT';

  // Petition Main Banner
  doc.setFillColor(...COLOR_LIGHT_BG);
  doc.setDrawColor(...COLOR_BORDER);
  doc.roundedRect(margin, currentY, pageWidth - (margin * 2), 16, 2, 2, 'FD');

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(10);
  doc.setTextColor(...COLOR_NAVY);
  doc.text(`Petition Number: ${petNumber}`, margin + 4, currentY + 6);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(8.5);
  doc.setTextColor(...COLOR_SLATE);
  doc.text(`Status: ${petition.status || 'Approved'}   |   Priority: ${petition.priority || 'MEDIUM'}   |   Assigned: ${petition.officerName || 'Officer'}`, margin + 4, currentY + 12);

