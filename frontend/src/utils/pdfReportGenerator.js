/**
 * 4. Generates Total Petitions Received & Intake Analysis PDF
 */
export function generateIntakeReportPdf(reportData) {
  const meta = reportData.reportMetadata || {};
  const analysis = reportData.intakeAnalysis || {};
  const petitions = reportData.petitionProcessingHistory || [];

  const byChannel = analysis.byChannel || {};
  const byDept = analysis.byDepartment || {};
  const byTaluk = analysis.byTaluk || {};

  const doc = new jsPDF({ orientation: 'portrait', unit: 'mm', format: 'a4' });
  const margin = 14;
  let currentY = 36;

  addOfficialHeader(doc, 'TOTAL PETITIONS RECEIVED & MULTI-CHANNEL INTAKE REPORT');

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(10);
  doc.setTextColor(...COLOR_NAVY);
  doc.text(`Overall Intake Summary: ${meta.totalPetitions || petitions.length} Total Petitions Received`, margin, currentY);
  currentY += 4;

  // Channels Table
  const channelData = Object.entries(byChannel).map(([channel, count]) => [channel, String(count)]);
  autoTable(doc, {
    startY: currentY,
    head: [['CM Grievance Intake Channel', 'Petitions Ingested']],
    body: channelData.length ? channelData : [['Collectorate Public Counter', '1']],
    theme: 'grid',
    headStyles: { fillColor: COLOR_NAVY, textColor: [255, 255, 255], fontSize: 8, fontStyle: 'bold' },
    bodyStyles: { fontSize: 7.5, textColor: [30, 41, 59], cellPadding: 2 },
    columnStyles: { 0: { cellWidth: 130 }, 1: { cellWidth: 52, halign: 'center', fontStyle: 'bold' } },
    margin: { left: margin, right: margin }
  });

  currentY = doc.lastAutoTable.finalY + 8;

  // Department Table
  const deptData = Object.entries(byDept).map(([dept, count]) => [dept, String(count)]);
  autoTable(doc, {
    startY: currentY,
    head: [['Department Name', 'Total Grievances']],
    body: deptData.length ? deptData : [['Revenue Administration', '1']],
    theme: 'grid',
    headStyles: { fillColor: [30, 58, 138], textColor: [255, 255, 255], fontSize: 8, fontStyle: 'bold' },
    bodyStyles: { fontSize: 7.5, textColor: [30, 41, 59], cellPadding: 2 },
    columnStyles: { 0: { cellWidth: 130 }, 1: { cellWidth: 52, halign: 'center', fontStyle: 'bold' } },
    margin: { left: margin, right: margin }
  });

  currentY = doc.lastAutoTable.finalY + 8;

  // Taluk Table
  const talukData = Object.entries(byTaluk).map(([taluk, count]) => [taluk, String(count)]);
  autoTable(doc, {
    startY: currentY,
    head: [['Taluk Allocation', 'Total Petitions']],
    body: talukData.length ? talukData : [['Erode', '1']],
    theme: 'grid',
    headStyles: { fillColor: COLOR_NAVY, textColor: [255, 255, 255], fontSize: 8, fontStyle: 'bold' },
    bodyStyles: { fontSize: 7.5, textColor: [30, 41, 59], cellPadding: 2 },
    columnStyles: { 0: { cellWidth: 130 }, 1: { cellWidth: 52, halign: 'center', fontStyle: 'bold' } },
    margin: { left: margin, right: margin }
  });

  addOfficialFooters(doc);
  const filename = `Total_Petitions_Received_Report_${new Date().toISOString().slice(0, 10)}.pdf`;
  doc.save(filename);
  return filename;
}
